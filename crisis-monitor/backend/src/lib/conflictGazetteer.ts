/**
 * Curated gazetteer of places and regions that appear in African conflict
 * reporting, each pinned to its own country.
 *
 * This is the first thing lib/africaGeo.ts consults when turning a place an
 * article names into map coordinates. It is looked up by (country, name) —
 * never scanned for across countries and never matched as a substring — so
 * an entry here can only ever place an event inside the country the article
 * itself says the event is in.
 *
 * `kind: "region"` entries are states/provinces/named conflict areas; their
 * coordinates are a rough centre and the map labels them as region-level,
 * not as an exact location.
 *
 * `aliases` carry the transliterations and alternate names actually used in
 * press (Mekelle/Mekele/Mek'ele, El Fasher/Al-Fashir, Timbuktu/Tombouctou).
 *
 * Checked by test/geo.test.ts: every entry must fall inside (or within the
 * border tolerance of) its stated country, and must agree with GeoNames to
 * within 40 km wherever GeoNames has the same place. Add to it whenever a
 * real, currently-reported location is found missing — the pipeline's audit
 * log (escalation_articles.geo_method) shows which place names are falling
 * back to estimates or region centroids.
 */

export interface GazetteerPlace {
  /** Display name as it should appear in a summary ("near Mekelle"). */
  name: string;
  /** ISO-3166-1 alpha-2 code. */
  country: string;
  lat: number;
  lon: number;
  kind?: "place" | "region";
  aliases?: string[];
}

const P = (country: string, name: string, lat: number, lon: number, aliases?: string[]): GazetteerPlace => ({ name, country, lat, lon, aliases });
const R = (country: string, name: string, lat: number, lon: number, aliases?: string[]): GazetteerPlace => ({ name, country, lat, lon, kind: "region", aliases });

