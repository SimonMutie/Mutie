/**
 * Where Strategic Analyses reads from: African think tanks, international think tanks that write on Africa,
 * individual analysts and their newsletters, and specialist outlets, each with the domains it writes on.
 *
 * `url` is the feed, or the site's homepage when the feed is found by discovery (lib/feedDiscovery.ts); sites with
 * no readable feed show in red under Sources & keywords and are retried weekly, never dropped silently.
 * `africa` marks sources whose output is about Africa as a whole, so a piece from them counts as about Africa even
 * when it names no country.
 */

export type DomainId = "humanitarian" | "geopolitics" | "elections" | "economy" | "trade" | "cyber" | "conflict";
export type SourceKind = "african" | "international" | "analyst" | "outlet";

export interface Source {
  name: string;
  url: string;
  africa: boolean;
  kind: SourceKind;
  domains: DomainId[];
}

